  /**
   * Get the Web Push subscription of the grant
   * The subscription that this grant (the access token and the tokens that refreshing it
   * issues) registered; a 404 when it has none. A subscription ends when the push service
   * reports it expired or the grant ends (sign-out, revocation, expiry).
   *
   *
   *
   * Returns:
   * 	[NetworkResult.Success] with [dev.mycroblog.core.api.models.PushSubscription] if the request was successful.
   * 	[NetworkResult.Failure] with a [NetworkError] if the request failed.
   */
  public suspend fun getPushSubscription(apiConfiguration: ApiConfiguration = ApiConfiguration()): NetworkResult<PushSubscription> {
    val basePath = apiConfiguration.basePath.trimEnd('/')
    val url = basePath + """/push/subscription"""

    return try {
      val response = httpClient.`get`(url) {
        `header`("Accept", "application/json")
        headers {
          apiConfiguration.customHeaders.forEach { (name, value) ->
            remove(name)
            append(name, value)
          }
        }
      }

      if (response.status.isSuccess()) {
        NetworkResult.Success(response.body())
      } else {
        val errorBody = response.bodyAsText().ifBlank { null }
        NetworkResult.Failure(NetworkError.Http(statusCode = response.status.value, statusDescription = response.status.description, body = errorBody))
      }
    } catch (e: ResponseException) {
      val status = e.response.status
      val body = runCatching { e.response.bodyAsText() }.getOrNull()?.ifBlank { null }
      NetworkResult.Failure(NetworkError.Http(status.value, status.description, body))
    } catch (e: IOException) {
      NetworkResult.Failure(NetworkError.Network(e))
    } catch (e: ContentConvertException) {
      NetworkResult.Failure(NetworkError.Serialization(e))
    } catch (e: NoTransformationFoundException) {
      NetworkResult.Failure(NetworkError.Serialization(e))
    } catch (e: CancellationException) {
      throw e
    } catch (e: Exception) {
      NetworkResult.Failure(NetworkError.Unknown(e))
    }
  }

  /**
   * Register the Web Push subscription of the grant
   * Registers the browser's push subscription (`PushSubscription.toJSON()`, subscribed with
   * the instance's `push_server_key`) for the user's notifications of the `alerts` types,
   * replacing the grant's earlier subscription and any subscription with the same endpoint.
   * Sending it again with other `alerts` changes the types. The endpoint must be an
   * `https` URL; an invalid endpoint, key, or type is a 422 that names the property. A 404
   * means that the instance sends no Web Push (`Instance.push_server_key` is omitted).
   *
   *
   * Parameters:
   * 	 @param pushSubscriptionRequest 
   * 	 @param idempotencyKey A key the client chooses per request, which makes the request safe to send again. Within
   * 24 hours, a request with a key that the same sign-in of the user in the same client (an
   * anonymous client: the same address) already sent to the operation gets the first answer
   * again instead of being carried out again. The same key with another request (another
   * path, query, or body) is a 422 `/api/v1/problems/idempotency-key-reused`, and a repeat
   * while the first request is still being carried out is a 409
   * `/api/v1/problems/idempotency-key-in-use` with a `Retry-After` of a second. Only an answer below 400 is kept: after a 4xx
   * or 5xx the key is free, so a request sent again with it is carried out. A key longer than
   * 256 characters, or one that is not UTF-8 without U+0000, is a 422.
   *
   * Returns:
   * 	[NetworkResult.Success] with [dev.mycroblog.core.api.models.PushSubscription] if the request was successful.
   * 	[NetworkResult.Failure] with a [NetworkError] if the request failed.
   */
